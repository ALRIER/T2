source('R/00_shared/load_all.R'); t2_load('.')
root <- tempfile('t2-size-'); Sys.setenv(T2_OUTPUT_ROOT=root, T2_MAX_FILE_MB='0.01')
big <- matrix(seq_len(5000L), ncol=10L)
t2_write_csv(big, file.path(root, 'big.csv'))
idx <- file.path(root, 'big.rds'); t2_atomic_save(list(values=big), idx)
files <- list.files(root, recursive=TRUE, full.names=TRUE)
stopifnot(length(files) > 2L, all(file.info(files)$size <= t2_max_file_bytes()))
stopifnot(identical(t2_read_rds(idx)$values, big))
unlink(root, recursive=TRUE)
cat('ARTIFACT SIZE CONTRACT PASS\n')
